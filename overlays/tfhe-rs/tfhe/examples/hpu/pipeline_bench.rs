fn main() -> ExitCode {
    let args = Args::parse();
    let run_id = args.run_id.clone().unwrap_or_else(|| unix_ms().to_string());

    let run_result = panic::catch_unwind({
        let args = args.clone();
        let run_id = run_id.clone();
        move || run(args, run_id)
    });

    match run_result {
        Ok(Ok(())) => ExitCode::SUCCESS,
        Ok(Err(err)) => {
            eprintln!("benchmark blocked: {err}");
            let _ = write_blocker_report(&args, &run_id, err);
            ExitCode::from(1)
        }
        Err(payload) => {
            let err = panic_payload_to_string(payload);
            eprintln!("benchmark blocked by panic: {err}");
            let _ = write_blocker_report(&args, &run_id, err);
            ExitCode::from(2)
        }
    }
}

fn run(args: Args, run_id: String) -> Result<(), String> {
    validate_args(&args)?;
    fs::create_dir_all(&args.results_dir)
        .map_err(|err| format!("unable to create results dir {:?}: {err}", args.results_dir))?;

    let dataset_size = effective_dataset_size(&args)?;
    if args.generate_input {
        generate_input_dataset(&args, dataset_size)?;
    }
    let input_kind = input_kind(&args);
    ensure_inputs_exist(&args, input_kind)?;

    let init_start = Instant::now();

    let t = Instant::now();
    let hpu_device = open_hpu_device(&args);
    let device_open_ns = elapsed_ns(t);

    let message_width = hpu_device.params().pbs_params.message_width;
    if args.integer_width % message_width != 0 {
        return Err(format!(
            "--integer-width {} is not divisible by HPU message width {}",
            args.integer_width, message_width
        ));
    }
    if !hpu_device
        .config()
        .firmware
        .integer_w
        .contains(&args.integer_width)
    {
        return Err(format!(
            "--integer-width {} is not enabled in HPU firmware config {:?}",
            args.integer_width,
            hpu_device.config().firmware.integer_w
        ));
    }
    let num_blocks = args.integer_width / message_width;

    let t = Instant::now();
    let prepared_input = prepare_input(&args, input_kind, dataset_size)?;
    let (cks, sks_compressed) = match &prepared_input {
        PreparedInput::Plaintext => {
            let cks = ClientKey::new(KeySwitch32PBSParameters::from(hpu_device.params()));
            let sks_compressed = CompressedServerKey::new_radix_compressed_server_key(&cks);
            (cks, sks_compressed)
        }
        PreparedInput::Ciphertext {
            client_key,
            server_key,
            ..
        } => (client_key.clone(), server_key.clone()),
    };
    let key_load_or_gen_ns = elapsed_ns(t);

    let t = Instant::now();
    tfhe::integer::hpu::init_device(&hpu_device, sks_compressed.clone())
        .map_err(|err| format!("HPU init_device failed: {err:?}"))?;
    let hpu_init_ns = elapsed_ns(t);

    let init = InitBreakdown {
        device_open_ns,
        key_load_or_gen_ns,
        hpu_init_ns,
        total_ns: elapsed_ns(init_start),
    };

    for warmup in 0..args.warmups {
        let _ = run_pipeline_repetition(
            &args,
            &run_id,
            warmup,
            input_kind,
            &prepared_input,
            dataset_size,
            &hpu_device,
            &cks,
            num_blocks,
        )?;
        hpu_device.mem_sanitizer();
    }

    let mut repetitions = Vec::with_capacity(args.repetitions);
    for rep in 0..args.repetitions {
        let result = run_pipeline_repetition(
            &args,
            &run_id,
            rep,
            input_kind,
            &prepared_input,
            dataset_size,
            &hpu_device,
            &cks,
            num_blocks,
        )?;
        repetitions.push(result);
        hpu_device.mem_sanitizer();
    }

    let report = Report {
        schema_version: "hpu-pipeline-bench/v1",
        generated_at_unix_ms: unix_ms(),
        run_id: run_id.clone(),
        args: args.clone(),
        environment: environment(),
        repo_inspection: repo_inspection(),
        stage_definitions: stage_definitions(),
        init,
        summary: summarize(&repetitions),
        repetitions,
    };

    let json_path = args.results_dir.join(format!("{run_id}.json"));
    let csv_path = args.results_dir.join(format!("{run_id}.csv"));
    write_json(&json_path, &report, args.sync_write)?;
    write_csv(&csv_path, &report.repetitions, args.sync_write)?;

    print_summary(&report);
    println!("raw_json={}", json_path.display());
    println!("raw_csv={}", csv_path.display());
    Ok(())
}

fn open_hpu_device(args: &Args) -> HpuDevice {
    let config_path = args.config.expand();
    if !args.no_reload {
        return HpuDevice::from_config(&config_path);
    }

    let mut config = HpuConfig::from_toml(&config_path);
    if let FFIMode::V80 { force_reload, .. } = &mut config.fpga.ffi {
        *force_reload = Some(ShellString::new("never".to_string()));
    }
    HpuDevice::new(config)
}

fn run_pipeline_repetition(
    args: &Args,
    run_id: &str,
    repetition: usize,
    input_kind: InputKind,
    prepared_input: &PreparedInput,
    dataset_size: usize,
    hpu_device: &HpuDevice,
    cks: &ClientKey,
    num_blocks: usize,
) -> Result<RepetitionResult, String> {
    let total_start = Instant::now();
    let mask = width_mask(args.integer_width);

    let t = Instant::now();
    let input_path = active_input_path(args, input_kind);
    let input_bytes = fs::read(input_path)
        .map_err(|err| format!("unable to read input {input_path:?}: {err}"))?;
    let ssd_read_ns = elapsed_ns(t);
    let input_len = input_bytes.len() as u64;

    let mut stages = StageBreakdown {
        ssd_read_ns,
        ..StageBreakdown::default()
    };

    let t = Instant::now();
    let plaintext_records = match input_kind {
        InputKind::PlaintextGeneratedOrRead => {
            parse_records(&input_bytes, dataset_size, args.integer_width, mask)?
        }
        InputKind::SerializedCiphertext => match prepared_input {
            PreparedInput::Ciphertext { plaintext, .. } => plaintext.clone(),
            PreparedInput::Plaintext => {
                unreachable!("prepared plaintext used with ciphertext mode")
            }
        },
    };
    let ciphertext_dataset = match input_kind {
        InputKind::PlaintextGeneratedOrRead => None,
        InputKind::SerializedCiphertext => Some(parse_ciphertext_dataset(
            &input_bytes,
            dataset_size,
            args.integer_width,
        )?),
    };
    stages.host_preprocessing_ns += elapsed_ns(t);

    let mut output_values = Vec::with_capacity(plaintext_records.len());
    let mut ciphertext_output_values = args
        .ciphertext_output
        .as_ref()
        .map(|_| Vec::with_capacity(plaintext_records.len()));
    let mut first_mismatch = None;

    for (batch_index, batch) in plaintext_records.chunks(args.batch_size).enumerate() {
        let t = Instant::now();
        let (lhs_cpu, rhs_cpu) = match ciphertext_dataset.as_ref() {
            Some(dataset) => {
                let start = batch_index * args.batch_size;
                let stop = start + batch.len();
                let mut lhs = Vec::with_capacity(batch.len());
                let mut rhs = match args.operand_mode {
                    OperandMode::EncryptedEncrypted => Some(Vec::with_capacity(batch.len())),
                    OperandMode::EncryptedClear => None,
                };
                for record_bytes in &dataset.ciphertext_record_bytes[start..stop] {
                    let pair: CiphertextPair = bincode::deserialize(record_bytes)
                        .map_err(|err| format!("unable to deserialize ciphertext record: {err}"))?;
                    lhs.push(pair.lhs);
                    if let Some(rhs) = rhs.as_mut() {
                        let rhs_ct = match args.clear_scalar {
                            Some(clear_scalar) => {
                                cks.encrypt_radix(clear_scalar & mask, num_blocks)
                            }
                            None => pair.rhs,
                        };
                        rhs.push(rhs_ct);
                    }
                }
                (lhs, rhs)
            }
            None => {
                let lhs = batch
                    .iter()
                    .map(|record| cks.encrypt_radix(record.lhs & mask, num_blocks))
                    .collect::<Vec<RadixCiphertext>>();
                let rhs = match args.operand_mode {
                    OperandMode::EncryptedEncrypted => Some(
                        batch
                            .iter()
                            .map(|record| {
                                cks.encrypt_radix(clear_rhs(args, record, mask), num_blocks)
                            })
                            .collect::<Vec<RadixCiphertext>>(),
                    ),
                    OperandMode::EncryptedClear => None,
                };
                (lhs, rhs)
            }
        };
        stages.host_preprocessing_ns += elapsed_ns(t);

        let t = Instant::now();
        let lhs_hpu = lhs_cpu
            .iter()
            .map(|ct| HpuRadixCiphertext::from_radix_ciphertext(ct, hpu_device))
            .collect::<Vec<_>>();
        let rhs_hpu = rhs_cpu.as_ref().map(|rhs| {
            rhs.iter()
                .map(|ct| HpuRadixCiphertext::from_radix_ciphertext(ct, hpu_device))
                .collect::<Vec<_>>()
        });
        stages.host_to_hpu_transfer_ns += elapsed_ns(t);

        let t = Instant::now();
        let mut hpu_results = Vec::with_capacity(batch.len());
        match (&args.operand_mode, rhs_hpu.as_ref()) {
            (OperandMode::EncryptedEncrypted, Some(rhs_hpu)) => {
                for (lhs, rhs) in lhs_hpu.iter().zip(rhs_hpu.iter()) {
                    hpu_results.push(exec_ct_ct(args.operation, lhs, rhs));
                }
            }
            (OperandMode::EncryptedClear, None) => {
                for (lhs, record) in lhs_hpu.iter().zip(batch.iter()) {
                    hpu_results.push(exec_ct_clear(
                        args.operation,
                        lhs,
                        clear_rhs(args, record, mask),
                    ));
                }
            }
            _ => unreachable!("operand mode and rhs HPU storage mismatch"),
        }
        for result in &hpu_results {
            result.wait();
        }
        stages.hpu_compute_ns += elapsed_ns(t);

        let t = Instant::now();
        let cpu_results = hpu_results
            .iter()
            .map(HpuRadixCiphertext::to_radix_ciphertext)
            .collect::<Vec<_>>();
        stages.hpu_to_host_transfer_ns += elapsed_ns(t);

        let t = Instant::now();
        for (offset, (record, ct)) in batch.iter().zip(cpu_results.iter()).enumerate() {
            let decrypted: u128 = cks.decrypt_radix(ct);
            let got = decrypted & mask;
            let rhs = rhs_for_reference(args, record, mask);
            let expected = reference(args.operation, record.lhs & mask, rhs, mask);
            if got != expected && first_mismatch.is_none() {
                first_mismatch = Some(format!(
                    "batch={batch_index},offset={offset},lhs=0x{:x},rhs=0x{:x},got=0x{:x},expected=0x{:x}",
                    record.lhs & mask,
                    rhs,
                    got,
                    expected
                ));
            }
            output_values.push(got);
        }
        stages.host_postprocessing_ns += elapsed_ns(t);

        if let Some(values) = ciphertext_output_values.as_mut() {
            values.extend(cpu_results);
        }
    }

    let mut output_bytes = 0;
    let mut ciphertext_output_bytes = 0;
    if args.output.is_some() || args.ciphertext_output.is_some() {
        let t = Instant::now();
        if let Some(output_path) = &args.output {
            output_bytes = write_output(output_path, &output_values, args)?;
        }
        if let (Some(ciphertext_output_path), Some(ciphertexts)) =
            (&args.ciphertext_output, ciphertext_output_values.as_ref())
        {
            ciphertext_output_bytes = write_ciphertext_output(
                ciphertext_output_path,
                ciphertexts,
                args.integer_width,
                args.sync_write,
            )?;
        }
        stages.ssd_writeback_ns += elapsed_ns(t);
    }

    stages.total_ns = elapsed_ns(total_start);
    let throughput_ops_per_s = if stages.total_ns == 0 {
        0.0
    } else {
        (plaintext_records.len() as f64) / (stages.total_ns as f64 / 1_000_000_000.0)
    };

    Ok(RepetitionResult {
        run_id: run_id.to_string(),
        repetition,
        operation: args.operation,
        operand_mode: args.operand_mode,
        integer_width: args.integer_width,
        dataset_size: plaintext_records.len(),
        batch_size: args.batch_size,
        input_kind,
        input_path: input_path.display().to_string(),
        plaintext_path: args
            .plaintext_input
            .as_ref()
            .map(|p| p.display().to_string()),
        ciphertext_path: args
            .ciphertext_input
            .as_ref()
            .map(|p| p.display().to_string()),
        output_path: args.output.as_ref().map(|p| p.display().to_string()),
        ciphertext_output_path: args
            .ciphertext_output
            .as_ref()
            .map(|p| p.display().to_string()),
        input_bytes: input_len,
        plaintext_bytes: plaintext_file_len(args).unwrap_or(0),
        output_bytes,
        ciphertext_output_bytes,
        throughput_ops_per_s,
        validation_passed: first_mismatch.is_none(),
        first_mismatch,
        stages,
    })
}

fn exec_ct_ct(
    operation: Operation,
    lhs: &HpuRadixCiphertext,
    rhs: &HpuRadixCiphertext,
) -> HpuRadixCiphertext {
    match operation {
        Operation::Add => lhs + rhs,
        Operation::Sub => lhs - rhs,
        Operation::Mul => lhs * rhs,
    }
}

fn exec_ct_clear(operation: Operation, lhs: &HpuRadixCiphertext, rhs: u128) -> HpuRadixCiphertext {
    match operation {
        Operation::Add => lhs + rhs,
        Operation::Sub => lhs - rhs,
        Operation::Mul => lhs * rhs,
    }
}

fn clear_rhs(args: &Args, record: &Record, mask: u128) -> u128 {
    args.clear_scalar.unwrap_or(record.rhs) & mask
}

fn rhs_for_reference(args: &Args, record: &Record, mask: u128) -> u128 {
    if let Some(clear_scalar) = args.clear_scalar {
        return clear_scalar & mask;
    }
    match args.operand_mode {
        OperandMode::EncryptedEncrypted => record.rhs & mask,
        OperandMode::EncryptedClear => clear_rhs(args, record, mask),
    }
}

fn reference(operation: Operation, lhs: u128, rhs: u128, mask: u128) -> u128 {
    match operation {
        Operation::Add => lhs.wrapping_add(rhs) & mask,
        Operation::Sub => lhs.wrapping_sub(rhs) & mask,
        Operation::Mul => lhs.wrapping_mul(rhs) & mask,
    }
}

fn validate_args(args: &Args) -> Result<(), String> {
    if args.dataset_size == 0 {
        return Err("--dataset-size must be greater than 0".to_string());
    }
    if args.batch_size == 0 {
        return Err("--batch-size must be greater than 0".to_string());
    }
    if args.repetitions == 0 {
        return Err("--repetitions must be greater than 0".to_string());
    }
    if args.integer_width == 0 || args.integer_width > 128 {
        return Err("--integer-width must be in 1..=128".to_string());
    }
    if matches!(args.plaintext_bytes, Some(0)) {
        return Err("--plaintext-bytes must be greater than 0".to_string());
    }
    let _ = effective_dataset_size(args)?;
    if args.ciphertext_input.is_some() {
        if args.generate_input {
            return Err(
                "--generate-input only applies to legacy --input mode; use hpu_pipeline_dataset for --ciphertext-input"
                    .to_string(),
            );
        }
        if args.plaintext_input.is_none() {
            return Err("--plaintext-input is required with --ciphertext-input".to_string());
        }
        if args.client_key.is_none() {
            return Err("--client-key is required with --ciphertext-input".to_string());
        }
        if args.server_key.is_none() {
            return Err("--server-key is required with --ciphertext-input".to_string());
        }
    } else if args.input.is_none() {
        return Err("--input is required unless --ciphertext-input is used".to_string());
    }
    Ok(())
}

fn effective_dataset_size(args: &Args) -> Result<usize, String> {
    if let Some(plaintext_bytes) = args.plaintext_bytes {
        let operand_bytes = args.integer_width.div_ceil(8);
        let record_bytes = operand_bytes * 2;
        if plaintext_bytes % record_bytes != 0 {
            return Err(format!(
                "--plaintext-bytes {plaintext_bytes} is not divisible by one lhs/rhs record ({record_bytes} bytes for {}-bit integers)",
                args.integer_width
            ));
        }
        let records = plaintext_bytes / record_bytes;
        if records == 0 {
            return Err(format!(
                "--plaintext-bytes {plaintext_bytes} is too small for one lhs/rhs record ({record_bytes} bytes)"
            ));
        }
        Ok(records)
    } else {
        Ok(args.dataset_size)
    }
}

