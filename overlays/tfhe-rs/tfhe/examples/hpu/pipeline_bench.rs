#[derive(Clone, Copy, Debug, Serialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
enum Operation {
    Add,
    Sub,
    Mul,
}

impl Operation {
    fn as_str(self) -> &'static str {
        match self {
            Self::Add => "add",
            Self::Sub => "sub",
            Self::Mul => "mul",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
enum OperandMode {
    /// lhs and rhs are encrypted, then the HPU executes ct op ct.
    EncryptedEncrypted,
    /// lhs is encrypted, rhs stays clear, then the HPU executes ct op scalar.
    EncryptedClear,
}

impl OperandMode {
    fn as_str(self) -> &'static str {
        match self {
            Self::EncryptedEncrypted => "encrypted-encrypted",
            Self::EncryptedClear => "encrypted-clear",
        }
    }
}

#[derive(Clone, Copy, Debug, Serialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
enum OutputFormat {
    Binary,
    Text,
}

#[derive(Parser, Debug, Clone, Serialize)]
#[command(long_about = "Benchmark SSD -> host -> V80 HPU TFHE -> host -> optional SSD writeback.")]
struct Args {
    /// HPU TOML top-level configuration file.
    #[arg(
        long,
        default_value = "${HPU_BACKEND_DIR}/config_store/${HPU_CONFIG}/hpu_config.toml"
    )]
    config: ShellString,

    /// Disable the V80 backend fresh-reload fallback. If the current hardware cannot be reused,
    /// the benchmark exits with a blocker report instead of unloading drivers or rescanning PCIe.
    #[arg(long)]
    no_reload: bool,

    /// Legacy cleartext input path. Use --plaintext-input/--ciphertext-input plus key files for
    /// the recommended generated-dataset workflow.
    #[arg(long)]
    input: Option<PathBuf>,

    /// Visible decimal cleartext file with one "lhs rhs" pair per line. Used as correctness
    /// reference and as scalar source for encrypted-clear mode.
    #[arg(long)]
    plaintext_input: Option<PathBuf>,

    /// Serialized CPU RadixCiphertext input file generated by hpu_pipeline_dataset.
    #[arg(long)]
    ciphertext_input: Option<PathBuf>,

    /// Client key file generated alongside --ciphertext-input.
    #[arg(long)]
    client_key: Option<PathBuf>,

    /// Compressed server key file generated alongside --ciphertext-input.
    #[arg(long)]
    server_key: Option<PathBuf>,

    /// Optional output path. If omitted, SSD writeback is skipped.
    #[arg(long)]
    output: Option<PathBuf>,

    /// Optional serialized CPU RadixCiphertext result output. This writes encrypted HPU results
    /// after HPU-to-host transfer.
    #[arg(long)]
    ciphertext_output: Option<PathBuf>,

    /// Number of binary operations/records to benchmark.
    #[arg(long, default_value_t = 1024)]
    dataset_size: usize,

    /// Logical fixed-width binary plaintext payload size in bytes. When set, this overrides
    /// --dataset-size for record-count calculation.
    #[arg(long)]
    plaintext_bytes: Option<usize>,

    /// Number of records processed before dropping HPU variables.
    #[arg(long, default_value_t = 64)]
    batch_size: usize,

    /// Measured steady-state repetitions.
    #[arg(long, default_value_t = 5)]
    repetitions: usize,

    /// Full pipeline warmup repetitions. Warmups are not written to raw results.
    #[arg(long, default_value_t = 1)]
    warmups: usize,

    /// Unsigned integer width. Must be supported by the loaded HPU firmware.
    #[arg(long, default_value_t = 64)]
    integer_width: usize,

    /// HPU operation to benchmark.
    #[arg(long, value_enum, default_value_t = Operation::Add)]
    operation: Operation,

    /// Operand form to benchmark.
    #[arg(long, value_enum, default_value_t = OperandMode::EncryptedEncrypted)]
    operand_mode: OperandMode,

    /// Constant rhs value. In encrypted-clear mode it is passed as a clear HPU scalar. In
    /// encrypted-encrypted mode it is encrypted on host and used as the rhs ciphertext.
    #[arg(long, value_parser = parse_cli_u128)]
    clear_scalar: Option<u128>,

    /// Deterministic input generator seed.
    #[arg(long, default_value_t = 0x5eed_u64)]
    seed: u64,

    /// Create or overwrite --input with deterministic cleartext pairs before measuring.
    #[arg(long)]
    generate_input: bool,

    /// Overwrite an existing input file when --generate-input is used.
    #[arg(long)]
    force: bool,

    /// Call fsync on output and result files.
    #[arg(long)]
    sync_write: bool,

    /// Output format for optional --output writeback.
    #[arg(long, value_enum, default_value_t = OutputFormat::Binary)]
    output_format: OutputFormat,

    /// Directory for raw CSV/JSON and summary JSON.
    #[arg(long, default_value = "target/hpu-pipeline-bench")]
    results_dir: PathBuf,

    /// Stable run id. Defaults to unix timestamp milliseconds.
    #[arg(long)]
    run_id: Option<String>,
}

