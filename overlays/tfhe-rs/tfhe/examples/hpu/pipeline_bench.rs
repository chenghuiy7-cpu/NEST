fn summarize(repetitions: &[RepetitionResult]) -> Summary {
    if repetitions.is_empty() {
        return Summary {
            measured_repetitions: 0,
            mean_total_ns: 0,
            min_total_ns: 0,
            max_total_ns: 0,
            mean_throughput_ops_per_s: 0.0,
            mean_stages_ns: StageBreakdown::default(),
        };
    }

    let mut mean = StageBreakdown::default();
    let mut min_total = u128::MAX;
    let mut max_total = 0;
    let mut throughput = 0.0;
    for rep in repetitions {
        let s = &rep.stages;
        mean.ssd_read_ns += s.ssd_read_ns;
        mean.host_preprocessing_ns += s.host_preprocessing_ns;
        mean.host_to_hpu_transfer_ns += s.host_to_hpu_transfer_ns;
        mean.hpu_compute_ns += s.hpu_compute_ns;
        mean.hpu_to_host_transfer_ns += s.hpu_to_host_transfer_ns;
        mean.host_postprocessing_ns += s.host_postprocessing_ns;
        mean.ssd_writeback_ns += s.ssd_writeback_ns;
        mean.total_ns += s.total_ns;
        min_total = min_total.min(s.total_ns);
        max_total = max_total.max(s.total_ns);
        throughput += rep.throughput_ops_per_s;
    }
    let n = repetitions.len() as u128;
    mean.ssd_read_ns /= n;
    mean.host_preprocessing_ns /= n;
    mean.host_to_hpu_transfer_ns /= n;
    mean.hpu_compute_ns /= n;
    mean.hpu_to_host_transfer_ns /= n;
    mean.host_postprocessing_ns /= n;
    mean.ssd_writeback_ns /= n;
    mean.total_ns /= n;

    Summary {
        measured_repetitions: repetitions.len(),
        mean_total_ns: mean.total_ns,
        min_total_ns: min_total,
        max_total_ns: max_total,
        mean_throughput_ops_per_s: throughput / repetitions.len() as f64,
        mean_stages_ns: mean,
    }
}

