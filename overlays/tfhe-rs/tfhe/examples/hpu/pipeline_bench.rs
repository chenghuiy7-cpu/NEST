fn prepare_input(
    args: &Args,
    input_kind: InputKind,
    dataset_size: usize,
) -> Result<PreparedInput, String> {
    match input_kind {
        InputKind::PlaintextGeneratedOrRead => Ok(PreparedInput::Plaintext),
        InputKind::SerializedCiphertext => {
            let plaintext_path = args
                .plaintext_input
                .as_ref()
                .expect("validated plaintext input path");
            let bytes = fs::read(plaintext_path).map_err(|err| {
                format!("unable to read plaintext input {plaintext_path:?}: {err}")
            })?;
            let plaintext =
                parse_text_records(&bytes, dataset_size, width_mask(args.integer_width))?;
            let client_key = read_bincode_file(
                args.client_key.as_ref().expect("validated client key path"),
                "client key",
            )?;
            let server_key = read_bincode_file(
                args.server_key.as_ref().expect("validated server key path"),
                "compressed server key",
            )?;
            Ok(PreparedInput::Ciphertext {
                plaintext,
                client_key,
                server_key,
            })
        }
    }
}

fn read_bincode_file<T: DeserializeOwned>(path: &Path, label: &str) -> Result<T, String> {
    let bytes = fs::read(path).map_err(|err| format!("unable to read {label} {path:?}: {err}"))?;
    bincode::deserialize(&bytes)
        .map_err(|err| format!("unable to deserialize {label} {path:?}: {err}"))
}

fn width_mask(width: usize) -> u128 {
    if width == 128 {
        u128::MAX
    } else {
        (1_u128 << width) - 1
    }
}

fn parse_records(
    bytes: &[u8],
    requested: usize,
    integer_width: usize,
    mask: u128,
) -> Result<Vec<Record>, String> {
    if bytes.starts_with(INPUT_MAGIC) {
        parse_binary_records(bytes, requested, integer_width, mask)
    } else {
        parse_text_records(bytes, requested, mask)
    }
}

fn parse_binary_records(
    bytes: &[u8],
    requested: usize,
    integer_width: usize,
    mask: u128,
) -> Result<Vec<Record>, String> {
    let header_len = 8 + 4 + 4 + 8 + 16;
    if bytes.len() < header_len {
        return Err("binary input is shorter than the HPU pipeline header".to_string());
    }
    let version = u32::from_le_bytes(bytes[8..12].try_into().unwrap());
    if version != FORMAT_VERSION {
        return Err(format!(
            "unsupported input format version {version}; expected {FORMAT_VERSION}"
        ));
    }
    let file_width = u32::from_le_bytes(bytes[12..16].try_into().unwrap()) as usize;
    if file_width != integer_width {
        return Err(format!(
            "input integer width {file_width} does not match --integer-width {integer_width}"
        ));
    }
    let count = u64::from_le_bytes(bytes[16..24].try_into().unwrap()) as usize;
    if count < requested {
        return Err(format!(
            "input contains {count} records but --dataset-size requested {requested}"
        ));
    }
    let record_bytes = &bytes[header_len..];
    if record_bytes.len() < count * 32 {
        return Err("binary input payload is truncated".to_string());
    }
    let mut records = Vec::with_capacity(requested);
    for i in 0..requested {
        let base = i * 32;
        let lhs = u128::from_le_bytes(record_bytes[base..base + 16].try_into().unwrap()) & mask;
        let rhs =
            u128::from_le_bytes(record_bytes[base + 16..base + 32].try_into().unwrap()) & mask;
        records.push(Record { lhs, rhs });
    }
    Ok(records)
}

fn parse_text_records(bytes: &[u8], requested: usize, mask: u128) -> Result<Vec<Record>, String> {
    let text = std::str::from_utf8(bytes)
        .map_err(|err| format!("input is neither HPU binary dataset nor UTF-8 text: {err}"))?;
    let mut values = Vec::new();
    for token in text.split_whitespace() {
        values.push(parse_u128_token(token)? & mask);
    }
    if values.len() < requested * 2 {
        return Err(format!(
            "text input has {} numeric tokens but {} are required for {} records",
            values.len(),
            requested * 2,
            requested
        ));
    }
    let mut records = Vec::with_capacity(requested);
    for pair in values.chunks_exact(2).take(requested) {
        records.push(Record {
            lhs: pair[0],
            rhs: pair[1],
        });
    }
    Ok(records)
}

fn parse_ciphertext_dataset(
    bytes: &[u8],
    requested: usize,
    integer_width: usize,
) -> Result<CiphertextDataset, String> {
    let header_len = 8 + 4 + 4 + 8 + 16;
    if bytes.len() < header_len {
        return Err("ciphertext input is shorter than the HPU ciphertext header".to_string());
    }
    if &bytes[0..8] != CIPHERTEXT_MAGIC {
        return Err("ciphertext input does not start with HPUCTX1 magic".to_string());
    }
    let version = u32::from_le_bytes(bytes[8..12].try_into().unwrap());
    if version != FORMAT_VERSION {
        return Err(format!(
            "unsupported ciphertext format version {version}; expected {FORMAT_VERSION}"
        ));
    }
    let file_width = u32::from_le_bytes(bytes[12..16].try_into().unwrap()) as usize;
    if file_width != integer_width {
        return Err(format!(
            "ciphertext integer width {file_width} does not match --integer-width {integer_width}"
        ));
    }
    let count = u64::from_le_bytes(bytes[16..24].try_into().unwrap()) as usize;
    if count < requested {
        return Err(format!(
            "ciphertext input contains {count} records but --dataset-size requested {requested}"
        ));
    }

    let mut offset = header_len;
    let mut ciphertext_record_bytes = Vec::with_capacity(requested);
    for index in 0..requested {
        if offset + 8 > bytes.len() {
            return Err(format!(
                "ciphertext input is truncated before record {index} length"
            ));
        }
        let len = u64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap()) as usize;
        offset += 8;
        if offset + len > bytes.len() {
            return Err(format!(
                "ciphertext input is truncated in record {index}: need {len} bytes"
            ));
        }
        ciphertext_record_bytes.push(bytes[offset..offset + len].to_vec());
        offset += len;
    }

    Ok(CiphertextDataset {
        ciphertext_record_bytes,
    })
}

fn parse_u128_token(token: &str) -> Result<u128, String> {
    if let Some(hex) = token
        .strip_prefix("0x")
        .or_else(|| token.strip_prefix("0X"))
    {
        u128::from_str_radix(hex, 16).map_err(|err| format!("invalid hex token {token:?}: {err}"))
    } else {
        token
            .parse::<u128>()
            .map_err(|err| format!("invalid decimal token {token:?}: {err}"))
    }
}

fn parse_cli_u128(token: &str) -> Result<u128, String> {
    parse_u128_token(token)
}

fn generate_input_dataset(args: &Args, dataset_size: usize) -> Result<(), String> {
    let input = args
        .input
        .as_ref()
        .ok_or_else(|| "--input is required with --generate-input".to_string())?;
    if input.exists() && !args.force {
        return Err(format!(
            "input {input:?} already exists; pass --force to overwrite it"
        ));
    }
    if let Some(parent) = input.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("unable to create input parent {parent:?}: {err}"))?;
    }
    let mask = width_mask(args.integer_width);
    let mut rng = StdRng::seed_from_u64(args.seed);
    let mut bytes = Vec::with_capacity(8 + 4 + 4 + 8 + 16 + dataset_size * 32);
    bytes.extend_from_slice(INPUT_MAGIC);
    bytes.extend_from_slice(&FORMAT_VERSION.to_le_bytes());
    bytes.extend_from_slice(&(args.integer_width as u32).to_le_bytes());
    bytes.extend_from_slice(&(dataset_size as u64).to_le_bytes());
    bytes.extend_from_slice(&(args.seed as u128).to_le_bytes());
    for _ in 0..dataset_size {
        let lhs = random_u128(&mut rng) & mask;
        let rhs = random_u128(&mut rng) & mask;
        bytes.extend_from_slice(&lhs.to_le_bytes());
        bytes.extend_from_slice(&rhs.to_le_bytes());
    }
    write_all(input, &bytes, args.sync_write)
}

fn random_u128(rng: &mut StdRng) -> u128 {
    ((rng.gen::<u64>() as u128) << 64) | (rng.gen::<u64>() as u128)
}

fn write_output(path: &Path, values: &[u128], args: &Args) -> Result<u64, String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("unable to create output parent {parent:?}: {err}"))?;
    }
    let bytes = match args.output_format {
        OutputFormat::Binary => {
            let mut bytes = Vec::with_capacity(8 + 4 + 4 + 8 + values.len() * 16);
            bytes.extend_from_slice(OUTPUT_MAGIC);
            bytes.extend_from_slice(&FORMAT_VERSION.to_le_bytes());
            bytes.extend_from_slice(&(args.integer_width as u32).to_le_bytes());
            bytes.extend_from_slice(&(values.len() as u64).to_le_bytes());
            for value in values {
                bytes.extend_from_slice(&value.to_le_bytes());
            }
            bytes
        }
        OutputFormat::Text => {
            let mut text = String::new();
            for value in values {
                use std::fmt::Write as _;
                writeln!(&mut text, "{value}").unwrap();
            }
            text.into_bytes()
        }
    };
    let len = bytes.len() as u64;
    write_all(path, &bytes, args.sync_write)?;
    Ok(len)
}

fn write_ciphertext_output(
    path: &Path,
    values: &[RadixCiphertext],
    integer_width: usize,
    sync: bool,
) -> Result<u64, String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|err| {
            format!("unable to create ciphertext output parent {parent:?}: {err}")
        })?;
    }
    let mut bytes = Vec::new();
    bytes.extend_from_slice(RESULT_CIPHERTEXT_MAGIC);
    bytes.extend_from_slice(&FORMAT_VERSION.to_le_bytes());
    bytes.extend_from_slice(&(integer_width as u32).to_le_bytes());
    bytes.extend_from_slice(&(values.len() as u64).to_le_bytes());
    bytes.extend_from_slice(&0_u128.to_le_bytes());
    for value in values {
        let record = bincode::serialize(value)
            .map_err(|err| format!("unable to serialize ciphertext output record: {err}"))?;
        bytes.extend_from_slice(&(record.len() as u64).to_le_bytes());
        bytes.extend_from_slice(&record);
    }
    let len = bytes.len() as u64;
    write_all(path, &bytes, sync)?;
    Ok(len)
}

fn write_all(path: &Path, bytes: &[u8], sync: bool) -> Result<(), String> {
    let mut file = File::create(path).map_err(|err| format!("unable to create {path:?}: {err}"))?;
    file.write_all(bytes)
        .map_err(|err| format!("unable to write {path:?}: {err}"))?;
    if sync {
        file.sync_all()
            .map_err(|err| format!("unable to fsync {path:?}: {err}"))?;
    }
    Ok(())
}

fn write_json<T: Serialize>(path: &Path, value: &T, sync: bool) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("unable to create json parent {parent:?}: {err}"))?;
    }
    let bytes = serde_json::to_vec_pretty(value)
        .map_err(|err| format!("unable to encode json {path:?}: {err}"))?;
    write_all(path, &bytes, sync)
}

